/* ==================================================================
 * font.h —— 汉字字库（片内基础 32 字 + 板载 W25Q 扩展字库）
 * ------------------------------------------------------------------
 * 【干什么】把 Unicode 码点换成一块 16×16 字模，交给 LCD_ShowGlyph16() 画出来。
 *
 * 【字从哪来 —— 2026-09-21 起是两层】
 *   ① **板载 W25Q 上的扩展字库**（`App/font_store.c` + `App/font_upload.c`）：
 *      GB2312 一级 3755 字，由 `Tools/font_xfer/` 从 PC 灌进去。装上之后**优先走它**。
 *   ② **片内基础 32 字**（`App/font_data.h`）：原来那 32 个字，**永远在**。
 *      扩展字库查不到、或者压根没装，就回退到它。
 *      ⇒ **没装字库时，屏上行为与改造前逐字一致** —— 这是本轮的验收判据之一。
 *
 * 【★ 返回值只在下一次调用前有效 —— 2026-09-21 改的，别按老习惯用】
 *   以前 `Font_Glyph16()` 返回的是**片内 Flash 的稳定指针**，存多久都行。
 *   现在两条路径都 memcpy 进**同一个 static scratch**，所以：
 *     · 返回值**只在下一次调用 `Font_Glyph16()` 之前有效**；
 *     · 相邻两次调用会**互相覆盖** ⇒
 *         a = Font_Glyph16(x);  b = Font_Glyph16(y);  之后再用 a
 *       画出来是 y 的字 —— **静默错误**，不报错、不崩。
 *     · 要留存字模，用 `Font_Glyph16Copy()` 抄进自己的缓冲。
 *   ★ 本函数**不可重入**：中断里调它会把正在画的那块字模踩掉
 *     （症状是偶发花字/串字，**零报错**）。
 *   ⚠️ 唯一调用点 `media.c:372` 是"查完立刻画、不缓存指针"，所以它**不受影响**
 *      —— 这也是这次能不改 `media.c` 一个字节的原因。
 *
 * 【字模格式 —— 和老的 LCD_Hzk 不是一套，别弄混】
 *     本字库：每个字 32 字节 = 16 行 × 2 字节；第 r 行 byte0 = x0..7、
 *             byte1 = x8..15，**高位在左**（bit7 = 最左边那点），1 = 笔画。
 *             —— 与 W25Q 上的 `FONT16.BIN` **故意保持一致**。
 *     老的 lcd_font.h 的 LCD_Hzk：**列优先**，每列 1 字节、bit0 = 最上面。
 *             （两者是转置关系。LCD_ShowChinese() 还是走老格式，没动它。）
 *
 * 【字体为什么锁死宋体 16px】拿 lcd_font.h 里那 6 个字（已在实物屏上验证过）
 *     做过对照：宋体 16px 逐位 100% 全等，黑体只有 43~58%。换字体 = 屏上
 *     已烧录的那 6 个字换字形，同时丢掉这个唯一的比对基准。见 gen.py 注释。
 *     （`Tools/font_gen/gen_bin.py` 生成 FONT16.BIN 时锁的是同一个字体/阈值。）
 *
 * 【ASCII 不在这】32~126 走 lcd_font.h 里现成的 8×16 点阵（LCD_ShowChar），
 *     不占这里的空间。
 * ================================================================== */
#ifndef __FONT_H
#define __FONT_H

#include "stm32f4xx.h"

#define FONT_W            16u      /* 字模宽（像素） */
#define FONT_H            16u      /* 字模高（像素） */
#define FONT_GLYPH_BYTES  32u      /* 每个字的字节数 = 16 行 × 2 字节 */

/* 查字模：cp = Unicode 码点。查到返回 32 字节字模指针，查不到返回 0。
 *
 * ★ 指针**只在下一次调用本函数之前有效**；本函数**不可重入** —— 理由见文件头。
 * ★ 查找顺序：单字缓存 → W25Q 扩展字库 → 片内 32 字。
 *   W25Q 里**没查到时一次 SPI 都不发**（索引在上电时已经进 RAM，二分全在 RAM 里走）。
 * ★ 码点必须 <= 0xFFFF —— 索引是 2 字节，超了会截断成另一个字，调用方自己要挡住
 *   （`media.c:372` 已经挡了）。 */
const uint8_t *Font_Glyph16(uint16_t cp);

/* 把字模**抄进调用方自己的缓冲**（32 字节）。返回 1 = 查到，0 = 没有。
 * ★ 要"留着以后用"就必须走这个，不能存 `Font_Glyph16()` 的返回值。 */
uint8_t Font_Glyph16Copy(uint16_t cp, uint8_t *out32);

/* 当前**有效**的字数：装了扩展字库就是它的字数，否则是片内 32。
 * （启动日志、屏上 `FONT:` 那一行、`/help` 都用它。） */
uint16_t Font_Count(void);

/* 字模现在从哪来：0 = 片内 32 字，1 = 板载 W25Q 扩展字库。
 * （屏上 `FONT:W25Q 3755` / `FONT:FLASH 32` 就是照它画的。） */
uint8_t Font_Source(void);

/* 让"上一个字模"的缓存失效。
 * ★ 字库被换掉 / 卸掉之后**必须**调它 —— 不调的话，那个码点会拿上一次字库的
 *   字模再画一次（一张页面上最多错一个字，而且不报错）。
 *   `font_upload.c` 在 `begin` 与 `end` 之后各调一次。 */
void Font_Invalidate(void);

#endif /* __FONT_H */
