/**
 * @file font.h
 * 用途：UTF-8 解码、ASCII 与汉字点阵检索以及文本绘制。
 * 使用：媒体绘制调用字体接口；优先使用初始化成功的外置字库，找不到的字符显示替代符。
 * 时序与边界：字符索引与字模位序必须匹配生成工具；UTF-8 字节数与屏幕字符宽度不是同一单位。
 * 接口说明：本头声明或内联接口；调用方包含后仍须按上述顺序初始化对应驱动。
 * 维护：修改协议/数据格式时同时核对另一端与 docs 中的约定；不依赖外层项目文件夹名称。
 */
#ifndef __FONT_H
#define __FONT_H

#include "stm32f4xx.h"

#define FONT_W 16u           /* 字模宽（像素） */
#define FONT_H 16u           /* 字模高（像素） */
#define FONT_GLYPH_BYTES 32u /* 每个字的字节数 = 16 行 × 2 字节 */

/* 查字模：cp = Unicode 码点。查到返回 32 字节字模指针，查不到返回 0。
 *
 *  指针**只在下一次调用本函数之前有效**；本函数**不可重入** —— 理由见文件头。
 *  查找顺序：单字缓存 → W25Q 扩展字库 → 片内 32 字。
 *   W25Q 里**没查到时一次 SPI 都不发**（索引在上电时已经进 RAM，二分全在 RAM 里走）。
 *  码点必须 <= 0xFFFF —— 索引是 2 字节，超了会截断成另一个字，调用方自己要挡住
 *   （`media.c:372` 已经挡了）。 */
const uint8_t *Font_Glyph16(uint16_t cp);

/* 把字模**抄进调用方自己的缓冲**（32 字节）。返回 1 = 查到，0 = 没有。
 *  要"留着以后用"就必须走这个，不能存 `Font_Glyph16()` 的返回值。 */
uint8_t Font_Glyph16Copy(uint16_t cp, uint8_t *out32);

/* 当前**有效**的字数：装了扩展字库就是它的字数，否则是片内 32。
 * （启动日志、屏上 `FONT:` 那一行、`/help` 都用它。） */
uint16_t Font_Count(void);

/* 字模现在从哪来：0 = 片内 32 字，1 = 板载 W25Q 扩展字库。
 * （屏上 `FONT:W25Q 3755` / `FONT:FLASH 32` 就是照它画的。） */
uint8_t Font_Source(void);

/* 让"上一个字模"的缓存失效。
 *  字库被换掉 / 卸掉之后**必须**调它 —— 不调的话，那个码点会拿上一次字库的
 *   字模再画一次（一张页面上最多错一个字，而且不报错）。
 *   `font_upload.c` 在 `begin` 与 `end` 之后各调一次。 */
void Font_Invalidate(void);

#endif /* __FONT_H */
