/* ============================================================================
 * wdg.h —— 独立看门狗（IWDG）接口
 *   ★ 2026-09-21 新建。**尚未加入工程**：没有登记进 MyAIMachines.uvprojx，
 *     也没有被任何文件引用（用户令："先不加入工程中"）。
 *   ⇒ 它现在的作用是把**接口和设计**钉下来，上板前不动别的东西一行。
 *
 * ============================================================================
 * ★★ 三个已经定死的决定（都有代码依据，改之前先读完）
 * ============================================================================
 *
 * 【决定 1】用 IWDG，不用 WWDG。三条理由：
 *   ① WWDG 最大超时只有 ~58 ms，而本工程单次阻塞动辄 11~14 秒（见下），
 *      差两个数量级 —— 装了只会不停咬。
 *   ② WWDG 挂在 APB1 上，主时钟一挂它跟着挂；IWDG 走**独立的 LSI**，
 *      正好能兜住"时钟/中断全死了"这种情况。
 *   ③ IWDG **没有中断**（Core/startup_stm32f40_41xxx.s 里只有 WWDG_IRQHandler，
 *      没有 IWDG_IRQHandler），它唯一的动作就是复位 —— 语义单一，不跟别的 ISR 抢。
 *
 * 【决定 2】★★ bootloader 里**一个字都不能写**。这是本模块最重要的一条。
 *   依据全在 Bootloader/boot_main.c：
 *     · :257-268  擦 Slot A（16+16+64 KB）"1~4 秒，CPU 全程被硬件拉停"
 *                 ⇒ **喂不进狗**，只能靠超时值兜；
 *     · :361-368  meta 只在**搬运成功之后**才从 READY 改成 CONFIRMED
 *                 ⇒ 擦到一半被复位，下次开机看到的还是 READY，会**再来一遍**；
 *     · :369-378  搬运失败会置 IAP_ST_FAILED 并 for(;;) **停住**；
 *     · :380-385  下次开机见 FAILED **不自动重试**，继续 for(;;)。
 *   ⇒ 于是只有两种结局，**两种都是坏的**：
 *     (a) 超时值 < 擦除时间 ⇒ 咬 → 复位 → 重擦 → 再咬 ⇒ **永久重启循环，
 *         板子永远起不来**（FAILED 那条路还要 ST-Link 才能救）；
 *     (b) 超时值 > 擦除时间 ⇒ 搬运期间它**根本不会咬** ⇒ 白装。
 *   **中间没有有用的档位** ⇒ bootloader 保持无狗。
 *
 * 【决定 3】只在 **App** 里启动，而且"喂狗点"是**三处**，不是一个位置。
 *   ★ IWDG 一旦启动就**只能靠复位关掉**（写 KR=0 无效）。
 *     所以 bootloader 不启 ⇒ App 才有的选；反过来 bootloader 一启，App 就永远
 *     甩不掉它，且**启动早于 WDG_Init() 的任何挂死都会变成死循环复位**。
 *     三处 = ① App 初始化序列里 WDG_Init() 一次  ② 主循环每圈 WDG_Feed()
 *            ③ 每个"整段阻塞"的函数内部也要 WDG_Feed()
 *
 * ----------------------------------------------------------------------------
 * 超时值怎么来的（★ 别凭感觉改）
 * ----------------------------------------------------------------------------
 *   下限由**"最长且喂不进去的操作"**决定，即 **IAP 擦 Slot B 的 1~4 秒**
 *   （iap_app.c 的 do_erase；同理，擦除期间 CPU 拉停）——
 *   **不是**由主循环圈速决定（这是最容易反的地方）。
 *   取 预分频 256 + 重装 2000 ⇒ 标称 16 s，对 4 s 有 4 倍余量。
 *
 *   ★★ 但要记住 **LSI 的精度是 ±50% 量级**（F4 手册：typ 32 kHz，范围 17~47 kHz）
 *     ⇒ "标称 16 s" 在 LSI 跑到 47 kHz 时**只剩约 10.9 s**。
 *     **所以别拿标称值当保证金，更不要靠把它调大去兜长阻塞。**
 *     ⇒ 正确做法：**能喂的长阻塞自己喂狗**；超时值只管"喂不进去"的那一处。
 *
 *   本工程已知的长阻塞（加喂狗点时别漏）：
 *     · IAP 擦 Slot B         1~4 s     ❌ 喂不进（CPU 拉停）⇒ 靠超时兜
 *     · 字库串口灌            11 s      ⚠️ 看实现：整段阻塞就得自己喂，
 *                                        每行回主循环则主循环那一次就够（要问 03）
 *     · MicRec 录制 + dump    13~14 s   ❌ 整段阻塞 ⇒ **必须自己喂**（归 01）
 *     · 刷屏 bmp_blit         150~300ms ✅ 主循环一圈盖得住
 *
 * ----------------------------------------------------------------------------
 * 两个必踩的副作用
 * ----------------------------------------------------------------------------
 *   ① **调试器单步时 IWDG 照跑 ⇒ 单步两秒板子就复位。**
 *      WDG_Init() 会置 DBGMCU->APB1FZ 的 DBG_IWDG_STOP 位，核 halted 时停表。
 *      ★ 注意 DebugConfig 目录里的 .dbgconf 那两行 DBG_IWDG_STOP / DBG_WWDG_STOP
 *        是**调试器侧的选项，不是同一个东西**，别以为设了就完事。
 *   ② **IAP_JUMP_TIMEOUT_MS = 15000**（iap_app.h:71，@IAP:COMMIT 后等 15 秒
 *      自动复位）落在标称 16 s 以内 —— **只差 1 秒**。
 *      ⇒ 谁把超时改到 15 s 以下，**升级成功也会在等 JUMP 时被狗咬掉**，
 *        现象是"升级看着成功了、板子自己复位了"。改超时值之前先看这一行。
 *
 * ----------------------------------------------------------------------------
 * ★ 上电顺序：**先修 PRIMASK，再装狗**
 * ----------------------------------------------------------------------------
 *   Bootloader/boot_main.c:186 的 __disable_irq() 之后**没有 __enable_irq()**
 *   ⇒ PRIMASK=1 原样带进 App ⇒ SysTick 冻住、GetTick_ms() 不前。
 *   现在这个 bug 的现象是"能打印、但什么都不动"；**装上 IWDG 之后，同一个 bug
 *   会变成"反复复位"** —— 更难查，但至少比静默不动更容易被发现。
 *   ⇒ 两道一起修才对得上，别只装狗。
 *
 * ----------------------------------------------------------------------------
 * ★★ 上板第一件事：**验它真的会咬**
 * ----------------------------------------------------------------------------
 *   本模块**没有**显式打开 LSI（RCC_LSICmd），因为 ST 官方的 IWDG 例程也不打 ——
 *   使能 IWDG 时硬件会强制打开 LSI。**但这一点我没上板验过。**
 *   ⇒ 上板必须做这一步：**故意去掉主循环里的 WDG_Feed()**，看板子是否在约 16 秒后
 *     复位（WDG_PrintResetCause() 会打出"上次是看门狗复位"）。
 *   ⇒ 不做这一步 = **不知道狗装没装上**（装了不咬是最坏的情况：以为有保护、其实没有）。
 *     若确实不咬，补救是在 WDG_Init() 里补 RCC_LSICmd(ENABLE) 并等 LSIRDY。
 *     用 WDG_Started() 可以随时把"狗到底启没启"打出来，不用靠相信。
 * ========================================================================= */
#ifndef __WDG_H
#define __WDG_H

#include "stm32f4xx.h"

/* --------------------------------------------------------------------------
 * 总开关：0 = 本模块**完全不起作用**（所有函数体被编译掉，一行机器码都不产生）
 *   ★ 默认 0 是刻意的：本模块"进了工程"和"被启用"是两件事，要分别点头。
 *     参照本工程既有做法：DHT11_PIN_ASSIGNED=0、PCA_AUTO_SWEEP、MIC_TRIG_SRC_NONE。
 * -------------------------------------------------------------------------- */
#define WDG_ENABLE            0

/* 预分频 = IWDG_Prescaler_256（stm32f4xx_iwdg.h 里那个 0x06），重装 2000
 * ⇒ 标称 2000 x 256 / 32 kHz = 16.0 s（LSI 偏差见头上那段，最坏约 10.9 s） */
#define WDG_PR_VALUE          0x06u
#define WDG_RELOAD_VALUE      2000u

void    WDG_Init(void);                    /* App 初始化序列里调**一次** */
void    WDG_Feed(void);                    /* 主循环每圈调一次 */
void    WDG_FeedLong(void);                /* ★ 见 .c：把"长操作"这个语义固定下来 */

uint8_t WDG_Started(void);                 /* 1 = 狗确实启了（用于把状态打出来验） */
uint8_t WDG_LastResetWasWatchdog(void);    /* 只读，不清标志。1 = 上次复位是狗咬的 */
void    WDG_ClearResetFlags(void);         /* 写 RMVF，清掉所有复位标志 */
void    WDG_PrintResetCause(void);         /* 打一行人话。★ 会顺带清标志 */

#endif /* __WDG_H */
