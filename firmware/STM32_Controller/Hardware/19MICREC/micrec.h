#ifndef __MICREC_H
#define __MICREC_H

#include "stm32f4xx.h"

/* ==================================================================
 * 录音（**RAM 版**）—— 把麦克风数据接住、存住、再从串口吐出来
 * ★ 2026-09-18 新增
 * ------------------------------------------------------------------
 * ★★ 为什么先做 RAM 版、而不是直接存 SD 卡：
 *   ① SD 卡的**写通路从没验证过** —— 到 2026-09-18 为止那张卡一条 CMD24
 *      都没成功发出去过（`Sd_WriteSelfTest()` 还没上机跑过）。录音依赖 SD
 *      写，等于把"麦克风数据对不对"和"卡写不写得动"两个未知数搅在一起，
 *      出问题分不清是谁的锅。
 *   ② RAM 版是 SD 版的**内核**：把左右交错的 I2S 流解成单声道、按半块攒、
 *      统计丢块……这部分代码两版一模一样，区别只在"攒到哪儿"。
 *   ③ 听的方式最快：SD 版要断电 → 拔卡 → 插读卡器才能听；RAM 版直接从
 *      串口吐到 PC 上就能放，**迭代一圈 1 分钟**。
 *   ⇒ 先用这一版确认"采到的确实是能听的人声"，再谈落盘。
 *
 * ------------------------------------------------------------------
 * ★ 串口命令（跟 `App/media.c` 的 `/xxx` 风格一致）
 *
 *   `/rec`        录 1 秒
 *   `/rec n`      录 n 秒（n 会被夹到 1~2）
 *   `/dump`       把**最近一次**录音以原始 PCM 吐到串口
 *   `/mic`        打一行录音状态（缓冲里有多少样本、上次丢了几块）
 *
 * ★ `/dump` 的线上格式（PC 端脚本 `Tools/micrec/dump2wav.py` 按这个解析）：
 *
 *     [DUMP] BEGIN <样本数> <PCM字节数>\r\n
 *     <2×PCM字节数 个十六进制字符，每行 64 个，行尾 \r\n>
 *     [DUMP] END <耗时>ms\r\n
 *
 *   ★★ 为什么吐**十六进制文本**，而不是原始字节（第一版是原始字节，已改）：
 *     原始 PCM 里**任何字节都可能出现**，包括 `\r` `\n` 和 "[DUMP] END" 这几个
 *     字符本身。而串口助手"保存接收数据到文件"如果走的是**文本模式**，会把
 *     `\r\n` 翻译成 `\n` —— 字节流被改过，音频直接变成一片噪声，而且**从表面
 *     看不出来**（字节数对不上，但一般人不会去数）。
 *     全是可打印 ASCII 就没有这个问题：怎么存都不变样，还能直接在终端里看。
 *     代价是传输量翻倍（1 秒录音约吐 6 秒、2 秒约 12 秒），测试够用。
 *
 *   ★ 先给长度仍然有价值：PC 端"数够 2×字节数 个十六进制字符就停"，
 *     既不用猜哪里是结尾，也不怕中间夹了日志。
 *
 * ------------------------------------------------------------------
 * ★★ 三条必须知道的限制：
 *
 *   ① **最多 2 秒**。缓冲是静态数组 `int16_t[32000]` = 64KB，占的是主 SRAM
 *      （128KB）。要录更长只有两条路：换压缩（ADPCM）、或落 SD 卡。
 *   ② **颗粒度 32ms**。数据是按"半块"（512 个样本 = 32ms）交付的，所以
 *      实际时长总会被凑成 32ms 的整数倍，不会正好是 1000ms。
 *   ③ **录音期间是阻塞的** —— 整个 `/rec` 期间主循环停在驱动里，不刷屏、
 *      不 printf、不读卡。
 *      这不是偷懒：麦克风的 DMA 环形缓冲**只有 64ms**，主循环里任何一个
 *      慢动作（刷一次状态页几毫秒、printf 排队）都会把半块冲掉，而丢包
 *      **不会报错**，只会让音频有破音/杂音 —— 极难查。
 *      阻塞 1~2 秒换来"一个样本都不丢"，对测试工具来说完全划算。
 *      （代价：这 1~2 秒里按 K-UP 不会切屏，秒表也停着。松手后照常。）
 *
 * ------------------------------------------------------------------
 * ★ 调用顺序（跟 inmp441 一样严）：
 *      TIM6_Init() → UART_Init() → INMP441_Init() → INMP441_Start()
 *      → 才能用本模块的全部命令
 *   本模块内部会 printf、也会用 GetTick_ms()，缺哪个都不行。
 * ================================================================== */

/* 最长能录几秒（缓冲大小由它决定：MIC_SAMPLE_RATE × 这个数 × 2 字节） */
#define MICREC_SEC_MAX      2u

/* ==================== 对外接口 ==================== */

/* 串口命令入口。**必须在 Media_Command() 之前调**（media 会把不认识的
 * `/xxx` 当成"未知命令"打一行，别人截不到就轮不到它了）。
 * 返回 1 = 这条命令是本模块的，已处理完，调用者不要再看；
 * 返回 0 = 不是本模块的命令，照常交给 Media_Command()。 */
uint8_t MicRec_Command(const char *line);

/* 说明：本模块**故意只暴露这一个函数**。缓冲里的样本数/上次的统计量
 * 都由 `/mic` 那一行直接打出来，不另开取值接口 —— 没有调用者的接口
 * 迟早会腐烂，等真有人要用（比如屏上做一行录音状态）再加。 */

#endif /* __MICREC_H */
